#!/usr/bin/env bash
# Regenerates src/codex/generated from the pinned Codex, or with --check fails when the committed copy differs.
set -euo pipefail

readonly SUPPORTED_VERSION="codex-cli 0.146.0"
readonly HEADER="// @generated by scripts/generate-codex-bindings.sh. Do not edit by hand."
readonly ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly TARGET="${ROOT}/src/codex/generated"

mode="write"
if [[ "${1:-}" == "--check" ]]; then
  mode="check"
elif [[ $# -gt 0 ]]; then
  echo "unknown argument \`$1\`; use --check or no argument" >&2
  exit 2
fi

found="$(codex --version)"
if [[ "${found}" != "${SUPPORTED_VERSION}" ]]; then
  echo "codex must be ${SUPPORTED_VERSION}, found \`${found}\`; install it with \`npm install -g @openai/codex@0.146.0\`" >&2
  exit 1
fi

staging="$(mktemp -d)"
trap 'rm -rf "${staging}"' EXIT
# --experimental keeps the methods Margin uses (for example thread/realtime and experimentalApi fields).
codex app-server generate-ts --experimental --out "${staging}"
while IFS= read -r -d '' file; do
  { echo "${HEADER}"; cat "${file}"; } > "${file}.tmp"
  mv "${file}.tmp" "${file}"
done < <(find "${staging}" -name '*.ts' -print0)

if [[ "${mode}" == "check" ]]; then
  diff -r "${staging}" "${TARGET}" > /dev/null || {
    echo "src/codex/generated is out of date; run scripts/generate-codex-bindings.sh and commit the result" >&2
    exit 1
  }
  exit 0
fi

rm -rf "${TARGET}"
mkdir -p "$(dirname "${TARGET}")"
mv "${staging}" "${TARGET}"
chmod 755 "${TARGET}"
